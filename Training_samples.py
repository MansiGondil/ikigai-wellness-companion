# Cell 4: Define the helper function to generate responses

def wellness_reply(user_text: str, temperature: float = 0.6, max_tokens: int = 250) -> str:
    """
    Sends the user's message to GPT-3.5 with our mental health system prompt
    and returns a supportive, empathetic response.
    """
    resp = client.chat.completions.create(
        model="gpt-3.5-turbo",
        messages=[
            {"role": "system", "content": MENTAL_HEALTH_SYSTEM_PROMPT},
            {"role": "user", "content": user_text}
        ],
        temperature=temperature,
        max_tokens=max_tokens
    )
    return resp.choices[0].message.content.strip()

